import { expect, test, type Page } from '@playwright/test'

const W = '/projects/demo-pharmacy/workshop'

async function fresh(page: Page, slide = '') {
  await page.goto('/')
  await page.evaluate(() => localStorage.clear())
  await page.goto(`${W}${slide ? `?slide=${slide}` : ''}`)
  await expect(page.getByTestId('slide-stage')).toBeVisible()
}

async function startSession(page: Page) {
  const panel = page.getByRole('complementary', { name: 'Facilitator panel' })
  if (!(await panel.isVisible())) await page.getByRole('button', { name: /Show facilitator panel/ }).click()
  await panel.getByRole('tab', { name: 'Session' }).click()
  await panel.getByRole('button', { name: 'Start session' }).click()
  await expect(page.getByText(/Live · WS-02/)).toBeVisible()
}

const saved = (page: Page) => expect(page.getByRole('status').filter({ hasText: 'All changes saved' })).toBeVisible()

test('inline wordsmithing autosaves, updates the deck immediately, and supports undo/redo', async ({ page }) => {
  await fresh(page, 'principle:gp-5')
  const title = page.getByRole('textbox', { name: 'GP-05 Title' })
  await title.fill('Value Beyond the Building')
  await saved(page)
  const rail = page.getByRole('navigation', { name: 'Slides' })
  await expect(rail).toContainText('GP-05 Value Beyond the Building')
  await page.getByRole('button', { name: /^Undo/ }).click()
  await expect(title).toHaveValue('Value Beyond Fulfillment')
  await expect(rail).toContainText('GP-05 Value Beyond Fulfillment')
  await page.getByRole('button', { name: /^Redo/ }).click()
  await expect(title).toHaveValue('Value Beyond the Building')
  await page.reload()
  await expect(page.getByRole('textbox', { name: 'GP-05 Title' })).toHaveValue('Value Beyond the Building')
})

test('review statuses and recording the Owner’s approval of the exact wording', async ({ page }) => {
  await fresh(page, 'principle:gp-3')
  await startSession(page)
  await page.getByRole('radio', { name: 'Needs Refinement' }).click()
  await expect(page.getByRole('navigation', { name: 'Slides' })).toContainText('Needs Refinement')
  await page.getByRole('textbox', { name: 'GP-03 Statement' }).fill('The facility absorbs growth and automation refresh without interrupting service.')
  await saved(page)
  await page.getByRole('button', { name: 'Record approval' }).click()
  const dlg = page.getByRole('dialog')
  await expect(dlg).toContainText('absorbs growth and automation refresh')
  // GP-03's accountable approver is preset and cannot be changed in the dialog.
  await expect(dlg.getByLabel('Approved by')).toBeDisabled()
  await expect(dlg.getByLabel('Approved by').locator('option:checked')).toHaveText('Dr. Morgan Ellery — Meridian Valley Health')
  await expect(dlg.getByRole('button', { name: 'Record approval' })).toBeDisabled()
  await dlg.getByRole('checkbox').check()
  await dlg.getByRole('button', { name: 'Record approval' }).click()
  await expect(page.getByTestId('slide-stage')).toContainText(/Adopted wording\s*approved by Dr. Morgan Ellery/i)
  // Approved wording is protected: no inline editor until a revision is started.
  await expect(page.getByRole('textbox', { name: 'GP-03 Statement' })).toHaveCount(0)
  await page.getByRole('button', { name: 'Revise wording' }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Start revision' }).click()
  await expect(page.getByRole('textbox', { name: 'GP-03 Statement' })).toBeVisible()
  await expect(page.getByRole('radio', { name: 'Proposed' })).toHaveAttribute('aria-checked', 'true')
})

test('add, duplicate, delete with undo, reorder, and merge principles', async ({ page }) => {
  await fresh(page, 'principle:gp-2')
  const rail = page.getByRole('navigation', { name: 'Slides' })
  await page.getByRole('button', { name: 'Add principle' }).click()
  await expect(page.getByRole('textbox', { name: 'GP-07 Title' })).toHaveValue('New principle')
  await page.goto(`${W}?slide=principle:gp-2`)
  await page.getByRole('button', { name: 'Duplicate' }).click()
  await expect(page.getByRole('textbox', { name: 'GP-08 Title' })).toHaveValue('One Seamless Operation (copy)')
  await page.getByRole('button', { name: 'Delete' }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'Delete' }).click()
  await expect(rail).not.toContainText('(copy)')
  await page.keyboard.press('Control+z')
  await expect(rail).toContainText('GP-08 One Seamless Operation (copy)')

  // Reorder with the keyboard (Alt+↑).
  await page.goto(`${W}?slide=principle:gp-6`)
  await expect(page.getByRole('textbox', { name: 'GP-06 Title' })).toBeVisible()
  const order = async () => (await rail.locator('li').allInnerTexts()).filter((t) => /GP-0[1-8]/.test(t)).map((t) => t.match(/GP-0\d/)![0])
  const before = await order()
  await page.keyboard.press('Alt+ArrowUp')
  await expect.poll(order).not.toEqual(before)
  expect((await order()).indexOf('GP-06')).toBe(before.indexOf('GP-06') - 1)

  // Merge GP-05 into GP-06.
  await page.getByRole('button', { name: 'Merge' }).click()
  const dlg = page.getByRole('dialog')
  await dlg.getByRole('checkbox', { name: 'Merge GP-05' }).check()
  await dlg.getByLabel('Title').fill('Speed, Certainty and Lasting Value')
  await dlg.getByRole('button', { name: /^Merge/ }).click()
  await expect(rail).not.toContainText('GP-05')
  await expect(page.getByRole('textbox', { name: 'GP-06 Title' })).toHaveValue('Speed, Certainty and Lasting Value')
})

test('Present mode: full-window slides, keyboard navigation, in-place editing, and back to Edit', async ({ page }) => {
  await fresh(page, 'winTheme:wt-1')
  await page.keyboard.press('p')
  await expect(page.getByTestId('present-mode')).toBeVisible()
  await expect(page.getByRole('navigation', { name: 'Slides' })).toHaveCount(0)
  await expect(page.getByRole('complementary', { name: 'Facilitator panel' })).toHaveCount(0)
  await expect(page.getByRole('textbox')).toHaveCount(0)
  await page.keyboard.press('ArrowRight')
  await expect(page.getByTestId('slide-stage')).toContainText('Precision at Scale')
  await page.keyboard.press('e')
  const stmt = page.getByRole('textbox', { name: 'WT-02 Vision statement' })
  await stmt.fill('Precision at Scale. Care at Every Step.')
  await stmt.press('Control+Enter')
  await expect(page.getByTestId('slide-stage')).toContainText('Care at Every Step.')
  await page.keyboard.press('Escape')
  await expect(page.getByRole('textbox')).toHaveCount(0)
  await page.keyboard.press('Escape')
  await expect(page.getByTestId('present-mode')).toHaveCount(0)
  await expect(page.getByRole('navigation', { name: 'Slides' })).toBeVisible()
  // Same slide in Edit mode.
  await expect(page.getByRole('textbox', { name: 'WT-02 Vision statement' })).toHaveValue('Precision at Scale. Care at Every Step.')
})

