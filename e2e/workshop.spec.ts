test('recovers unsaved edits after an interrupted session', async ({ page }) => {
  await fresh(page, 'principle:gp-5')
  const title = page.getByRole('textbox', { name: 'GP-05 Title' })
  await title.fill('Value Beyond Fulfillment and Beyond')
  // Reload before the autosave delay elapses (simulates a crash or closed tab).
  await page.reload()
  await expect(page.getByRole('alert').filter({ hasText: 'Recovered 1 unsaved edit' })).toBeVisible()
  await expect(page.getByRole('textbox', { name: 'GP-05 Title' })).toHaveValue('Value Beyond Fulfillment and Beyond')
  await page.getByRole('button', { name: 'Save recovered edits' }).click()
  await saved(page)
  await page.reload()
  await expect(page.getByRole('textbox', { name: 'GP-05 Title' })).toHaveValue('Value Beyond Fulfillment and Beyond')
  await expect(page.getByText(/Recovered \d unsaved/)).toHaveCount(0)
})

test('meeting summary is generated from the session and exports to PDF', async ({ page }) => {
  await fresh(page, 'principle:gp-6')
  await startSession(page)
  await page.getByRole('button', { name: 'Record approval' }).click()
  const dlg = page.getByRole('dialog')
  await dlg.getByRole('checkbox').check()
  await dlg.getByRole('button', { name: 'Record approval' }).click()
  await expect(page.getByTestId('slide-stage')).toContainText('approved by Priya Ramanathan')
  const panel = page.getByRole('complementary', { name: 'Facilitator panel' })
  await panel.getByRole('tab', { name: 'Notes' }).click()
  await panel.getByLabel('New action').fill('Circulate adopted principles to the steering group')
  await panel.getByLabel('Action owner').fill('BSA')
  await panel.getByRole('button', { name: 'Add' }).click()
  await panel.getByRole('tab', { name: 'Session' }).click()
  await panel.getByRole('button', { name: 'End session' }).click()
  await page.getByRole('dialog').getByRole('button', { name: 'End session' }).click()
  await panel.getByRole('button', { name: 'Meeting summary' }).click()
  const sum = page.getByRole('dialog')
  await expect(sum).toContainText('Adopted — exact approved wording (1)')
  await expect(sum).toContainText('Speed with Certainty')
  await expect(sum).toContainText('Circulate adopted principles')
  const [dl] = await Promise.all([page.waitForEvent('download'), sum.getByRole('button', { name: 'Download PDF' }).click()])
  expect(dl.suggestedFilename()).toMatch(/workshop-summary-WS-02.*\.pdf$/)
})

